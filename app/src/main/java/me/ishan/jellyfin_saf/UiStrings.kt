enum class AppLanguage(val id: String) {
	AUTO("auto"), ENGLISH("en"), CHINESE("zh"), JAPANESE("ja");
	
	companion object {
		fun fromId(id: String?): AppLanguage =
			entries.firstOrNull { it.id == id } ?: AUTO
		
		fun resolve(setting: AppLanguage): AppLanguage = when (setting) {
			AUTO -> when (Locale.getDefault().language) {
				"zh" -> CHINESE
				"ja" -> JAPANESE
				else -> ENGLISH
			}
			
			else -> setting
		}
		
		fun strings(setting: AppLanguage): UiStrings = when (resolve(setting)) {
			CHINESE -> ZH
			JAPANESE -> JA
			else -> EN
		}
	}
}
